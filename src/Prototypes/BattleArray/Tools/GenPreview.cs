// 排兵布阵 预览场景生成器：把造型源场景与真模型（.glb）摆进自带相机/灯光/环境的舞台，供近景看剪影与动作。
// 舞台本体在 src/Tools/PreviewStage.cs —— 这里只有"摆哪些件、机位在哪"。
//
// 用法：dotnet run --project src/Tools -- preview BattleArray <项目根> [动作名，默认 walk]
// 动作要在这一排里看相位差：游戏运行时各走各的，单摆一个一眼看不出走路循环对不对。

#nullable enable
using System;
using System.Collections.Generic;
using System.IO;
using DemoFactory.Tools;

namespace DemoFactory.Tools.BattleArray;

public static class GenPreview
{
    private const string Rigs = "src/Prototypes/BattleArray/Tools/Rigs";
    private const string Models = "src/Prototypes/BattleArray/Models";

    public static int Run(string root, string? clipArg)
    {
        if (string.IsNullOrEmpty(root))
            throw new ArgumentException("usage: dotnet run --project src/Tools -- preview BattleArray <project-root> [动作名，默认 walk]");
        var clip = string.IsNullOrEmpty(clipArg) ? "walk" : clipArg;
        var dir = $"{root}/{Rigs}";
        var genNote = "GENERATED BY src/Prototypes/BattleArray/Tools/Gen.cs — 勿手改；"
                      + "改脚本后跑 dotnet run --project src/Tools -- preview BattleArray <项目根>";
        string U(string p) => $"{Rigs}/{p}";

        // 八张兵种卡（与 ExportModels.gd 同一张名单）：骑手站得宽，间距给 2.2 米才不互相挡
        var cards = new[] { "HumanArcher", "HumanRider", "HumanTank", "HumanWarrior",
            "OrcArcher", "OrcRider", "OrcTank", "OrcWarrior" };
        var rigs = new List<PreviewStage.Item>();
        var glbs = new List<PreviewStage.Item>();
        for (var i = 0; i < cards.Length; i++)
        {
            rigs.Add(new PreviewStage.Item(cards[i], U($"Units/{cards[i]}.tscn"), i * 2.2));
            glbs.Add(new PreviewStage.Item(cards[i], $"{Models}/{cards[i]}.glb", i * 2.2, Ry: i % 3 * 35));
        }

        // 源场景（.tscn，未导出的灰盒）：八格站成一排比剪影 —— M2/M3 的验收面就是这张
        PreviewStage.PreviewScene(new PreviewStage.PreviewInput(
            File: Path.Join(dir, "_PreviewUnits.tscn"), RootName: "PreviewUnits",
            Uid: Uids.Uid.GetValueOrDefault("PreviewUnits"), GenNote: genNote,
            SunEul: new[] { -52.0, -28.0, 0.0 },
            Cam: new PreviewStage.Cam(new[] { 7.7, 2.6, 12.5 }, new[] { 7.7, 1.0, 0.0 }, 45),
            Items: rigs));

        // 真模型（.glb）验收台：八件各摆一个，根节点脚本把第三个参数指定的动作播起来
        PreviewStage.PreviewScene(new PreviewStage.PreviewInput(
            File: Path.Join(root, "src/Prototypes/BattleArray/Scenes/_PreviewModels.tscn"),
            RootName: "PreviewModels",
            Uid: Uids.Uid.GetValueOrDefault("PreviewModels"), GenNote: genNote,
            SunEul: new[] { -52.0, -28.0, 0.0 },
            RootScript: "src/GugaFramework/Tools/glb/preview_autoplay.gd",
            RootProps: new Dictionary<string, string> { ["clip"] = Tscn.JsonStr(clip) },
            Cam: new PreviewStage.Cam(new[] { 7.7, 3.0, 15.5 }, new[] { 7.7, 1.0, 0 }, 42),
            Items: glbs));
        return 0;
    }
}
