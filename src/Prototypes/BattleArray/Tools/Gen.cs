    private static Tscn.EmitResult BuildHumanWarrior(string root)
    {
        return Emit(PathDef.Units(root), "HumanWarrior", r =>
        {
            var g = Humanoid.Rig(r, h: 1.78, bulk: 1.06, arm: 0.58,
                matBody: "hWarrior", matCloth: "leather", matSkin: "skin",
                armYawL: -34, armYawR: -6);
            var J = g.J;
            var B = g.B;
            double U(double v) => v * g.U;

