            B.ConeEnd(sword, "tip", "steel", new[] { 0.0, 0.61, 0.0 }, 0.07, 0.11);

            // 圆盾随前抬的左臂升到胸前（返修①）：Grip 反手转回 +34° 把盘面立正，
            // 再往人物外侧让 0.02 米，让剑与盾在正视图里各走各的一条线。
            var shield = B.Grip(J["handL"], "Shield", new[] { 34.0, 0.0, -8.0 });
