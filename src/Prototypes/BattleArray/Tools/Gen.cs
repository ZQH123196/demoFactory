            B.Box(J["chest"], "trim", "gold", new[] { 0.0, -0.03, 0.17 }, new[] { 0.40, 0.04, 0.04 });
            Pauldron(B, J, "L", -1, "iron");
            Pauldron(B, J, "R", 1, "iron");
            B.Box(J["hips"], "scabbard", "leatherD", new[] { -0.20, -0.04, -0.06 }, new[] { 0.08, 0.10, 0.44 },
                Humanoid.O(rx: 14));

            // 剑握在右手、剑尖斜指向上前方：整组姿势只在 Grip 这一处转，调手臂时剑跟着走
            var sword = B.Grip(J["handR"], "Sword", new[] { 46.0, 0.0, -6.0 });
            B.CylEnd(sword, "grip", "leatherD", new[] { 0.0, -0.11, 0.0 }, 0.055, 0.15);
            B.Box(sword, "pommel", "gold", new[] { 0.0, -0.13, 0.0 }, new[] { 0.07, 0.05, 0.07 });
            B.Box(sword, "guard", "iron", new[] { 0.0, 0.03, 0.0 }, new[] { 0.20, 0.04, 0.06 });
