            B.Box(J["head"], "cheekL", "steel", new[] { -0.16, 0.08, 0.05 }, new[] { 0.06, 0.16, 0.18 });
            B.Box(J["head"], "cheekR", "steel", new[] { 0.16, 0.08, 0.05 }, new[] { 0.06, 0.16, 0.18 });
