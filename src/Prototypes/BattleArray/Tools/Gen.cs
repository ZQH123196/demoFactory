    // ============================================================
    //  人族 · 弓手（M2）
    //  剪影记号：**左手托一张立着的长弓** + 背后箭袋 + 兜帽。
    //  手臂的 rest 保持下垂（不给 armYawL）——托弓这个动作本来就在 attack_shoot 轨道里，
