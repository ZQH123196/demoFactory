            B.Cyl(bow, "limbDn", "woodD", new[] { 0.0, -0.16, 0.05 }, 0.05, 0.30, Humanoid.O(rx: -10));
            B.Box(bow, "string", "bone", new[] { 0.0, 0.20, -0.02 }, new[] { 0.014, 0.92, 0.014 },
                Humanoid.O(flat: true));
            B.Box(bow, "tipUp", "iron", new[] { 0.0, 0.80, 0.14 }, new[] { 0.05, 0.07, 0.05 },
                Humanoid.O(flat: true));
            B.Box(bow, "tipDn", "iron", new[] { 0.0, -0.18, 0.02 }, new[] { 0.05, 0.07, 0.05 },
                Humanoid.O(flat: true));

            // 右腰一把短刀（近战备手），挂在 hips 上
            B.Box(J["hips"], "scabbard", "leatherD", new[] { 0.20, -0.06, -0.02 }, new[] { 0.07, 0.09, 0.34 },
                Humanoid.O(rx: 10));

            Humanoid.Anchor(r, g.Top + U(0.20), U(1.05));
        });
