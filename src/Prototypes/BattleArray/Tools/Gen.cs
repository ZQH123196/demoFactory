    // ============================================================
    private static Tscn.EmitResult BuildHumanArcher(string root)
    {
        return Emit(PathDef.Units(root), "HumanArcher", r =>
        {
            var g = Humanoid.Rig(r, h: 1.74, bulk: 0.92, arm: 0.58,
                matBody: "hArcher", matCloth: "leather", matSkin: "skin", armYawR: -4);
            var J = g.J;
            var B = g.B;
            double U(double v) => v * g.U;

            // 兜帽：球壳压住头顶与后颈，前脸留出（rig 自带的 face 露在外面）
            B.Sph(J["head"], "hood", "hArcher", new[] { 0.0, 0.16, -0.05 }, new[] { 0.40, 0.34, 0.34 });
            B.Box(J["head"], "hoodPeak", "hArcher", new[] { 0.0, 0.30, -0.14 }, new[] { 0.22, 0.10, 0.16 });
            B.Box(J["head"], "band", "leatherD", new[] { 0.0, 0.20, 0.02 }, new[] { 0.38, 0.05, 0.34 });
            B.Box(J["chest"], "jerkin", "leather", new[] { 0.0, 0.04, 0.01 }, new[] { 0.42, 0.24, 0.28 });
            B.Box(J["hips"], "belt", "leatherD", new[] { 0.0, 0.10, 0.0 }, new[] { 0.44, 0.07, 0.30 });

            // 箭袋挂在**腰后**、筒口朝上但矮过肩。第一版挂在 chest 上，筒口从头顶探出来，
            // 正视图读成头顶一块棕色的帽子（体检单实测）。
            var quiver = B.Grip(J["hips"], "Quiver", new[] { -14.0, 0.0, 10.0 });
            B.Cyl(quiver, "tube", "leatherD", new[] { 0.12, -0.02, -0.18 }, 0.13, 0.34);
            B.Cyl(quiver, "tubeRim", "iron", new[] { 0.12, 0.28, -0.18 }, 0.15, 0.05);
            for (var i = 0; i < 3; i++)
            {
                var ax = 0.12 + (i - 1) * 0.045;
                B.Cyl(quiver, "shaft" + (i + 1), "woodD", new[] { ax, 0.30, -0.18 }, 0.02, 0.20);
                B.Cyl(quiver, "fletch" + (i + 1), "cloth", new[] { ax, 0.42, -0.18 }, 0.055, 0.09);
