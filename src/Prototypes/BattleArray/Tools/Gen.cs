    /// <summary>
    /// 肩甲（返修②）：一片球壳压住肩关节、圆心落在肩与胸的交界，再垂一片甲叶盖住大臂上沿 ——
    /// 原来那两颗小球只挂在肩关节上，正侧视图里与躯干之间留一条缝，就读成"浮着"。
    /// </summary>
    /// <param name="sgn">人物左右侧：左 ＝ -1（-X 为外），右 ＝ +1。</param>
    /// <param name="k">体量系数，重甲兵种给 1.1~1.2。</param>
    private static void Pauldron(HumanoidBrush B, Dictionary<string, string> J, string side, double sgn,
        string mat = "steel", double k = 1)
    {
        var j = J["shoulder" + side];
        B.Sph(j, "pauldron" + side, mat, new[] { sgn * 0.03, -0.04, 0.0 },
            new[] { 0.30 * k, 0.24 * k, 0.30 * k });
        B.Box(j, "pauldronLame" + side, mat, new[] { sgn * 0.05, -0.18, 0.0 },
            new[] { 0.24 * k, 0.11, 0.27 * k }, Humanoid.O(rz: sgn * -6));
    }

    /// <summary>M2 人族四条建满后接 M3 兽人四条（骑手各排本族最后一条）。登记进 ExportModels.gd 的那张表要同步。</summary>
    public static int Run(string root)
    {
        if (string.IsNullOrEmpty(root))
            throw new ArgumentException("usage: dotnet run --project src/Tools -- gen BattleArray <project-root>");
        var built = new List<Tscn.EmitResult>
        {
            BuildHumanWarrior(root),
            BuildHumanTank(root),
            BuildHumanArcher(root),
            BuildHumanRider(root),
            BuildOrcTank(root),
            BuildOrcWarrior(root),
            BuildOrcArcher(root),
            BuildOrcRider(root),
        };
        var total = 0;
        foreach (var b in built)
        {
            Console.WriteLine($"{b.RootName.PadRight(14)} {b.Count.ToString().PadLeft(4)} nodes");
            total += b.Count;
        }
        Console.WriteLine($"--- total {total} nodes / {built.Count} scenes");
        return 0;
    }
