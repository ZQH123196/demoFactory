    /// <summary>兽人共用的种族记号：獠牙从下颌翻出来 + 一道眉骨 + 一束发。四条卡都调它。</summary>
    private static void OrcFlesh(HumanoidBrush B, Dictionary<string, string> J, string matHair)
    {
        // 牙是"向上"的部件：ConeEnd 的 end 是底，h 沿局部 +Y 走，rx 正 ＝ 往前倒、rz 正 ＝ 往 -X 倒。
        // 起点的 y 给到下颌（-0.01）而不是脸中间 —— 第一版画在 y 0.015 被眉骨与盔壳挡住，正视图看不见牙。
        B.ConeEnd(J["head"], "tuskL", "bone", new[] { -0.075, -0.01, 0.15 }, 0.06, 0.14,
            Humanoid.O(rx: 30, rz: -12));
        B.ConeEnd(J["head"], "tuskR", "bone", new[] { 0.075, -0.01, 0.15 }, 0.06, 0.14,
            Humanoid.O(rx: 30, rz: 12));
        B.Box(J["head"], "brow", "orcSkin", new[] { 0.0, 0.215, 0.05 }, new[] { 0.36, 0.09, 0.22 });
        B.Box(J["head"], "topknot", matHair, new[] { 0.0, 0.30, -0.10 }, new[] { 0.13, 0.15, 0.18 });
    }

