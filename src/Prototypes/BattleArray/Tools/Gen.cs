            // 弓身居中挂在垂下的手上，下半截会插进地里（第一版实测），
            // 而且 attack_shoot 把手臂抬到 -80° 时居中挂的弓正好横在脸前。
            var bow = B.Grip(J["handL"], "Bow", new[] { 0.0, 0.0, 8.0 });
