            Q.Box(M["head"], "bit", "iron", new[] { 0.0, -0.04, 0.15 }, new[] { 0.19, 0.035, 0.035 });

            // ---- 骑手：座位组的落点 ＝ 鞍面高度 − 髋高 ⇒ 髋正好坐在鞍面上 ----
            // 大腿前摆 30°、膝再弯回 26°（小腿基本竖直）、两腿各向外开 34° —— 开不够就陷在马身里，
            // 第一版给 26°，十视图看不见腿，只看见一个人嵌在马背上。
            var hipY = Humanoid.HipY(riderH);
            var seatY = q.SaddleY - hipY; // 骑手所在平面的离地高度 —— 锚点要吃这个数，不能吃骑手自己的 Top
            var seat = Tscn.GrpT("Seat", M["saddle"], new[] { 0.0, -hipY, 0.0 });
            var g = Humanoid.Rig(seat, h: riderH, bulk: riderBulk, arm: 0.56, lean: lean,
                matBody: matRider, matCloth: matRiderCloth, matSkin: matSkin,
                thighYaw: -30, kneeYaw: 26, armYawL: -40, armYawR: -10, legSpread: 34);
            var J = g.J;
            var B = g.B;
            double U(double v) => v * g.U;

            if (ork)
            {
                // 兽人骑手不戴盔：一束发 + 两根獠牙就是记号（与对位人族骑兵差一颗头盔的剪影）
                OrcFlesh(B, J, "furD");
                B.Box(J["head"], "cap", "leather", new[] { 0.0, 0.25, -0.02 }, new[] { 0.34, 0.11, 0.34 });
            }
            else
            {
                B.Sph(J["head"], "helm", matSteel, new[] { 0.0, 0.17, 0.02 }, new[] { 0.40, 0.36, 0.40 });
                B.Box(J["head"], "brim", "iron", new[] { 0.0, 0.14, 0.13 }, new[] { 0.40, 0.05, 0.15 });
            }

            B.Box(J["chest"], "cuirass", matRider, new[] { 0.0, 0.05, 0.02 }, new[] { 0.46, 0.22, 0.30 });
            Pauldron(B, J, "L", -1, matSteel);
            Pauldron(B, J, "R", 1, matSteel);

            // 左手牵缰：一段短缰绳从拳头伸向马颈方向（rig 的缰绳不随马头动，只做"牵着"的读法）
            var rein = B.Grip(J["handL"], "Rein", new[] { 44.0, 0.0, 0.0 });
            B.CylEnd(rein, "reinLine", "leatherD", new[] { 0.0, 0.0, 0.0 }, 0.03, 0.46, Humanoid.O(rx: 58));

            // 右手横刀：刃朝前下，长度压在坐骑身长之内（占地上限 3.0 米吃的是 X/Z 最大边）
            var sabre = B.Grip(J["handR"], "Sabre", new[] { 34.0, 0.0, -8.0 });
            B.CylEnd(sabre, "grip", "leatherD", new[] { 0.0, -0.10, 0.0 }, 0.055, 0.14);
            B.Box(sabre, "guard", matTrim, new[] { 0.0, 0.03, 0.0 }, new[] { 0.16, 0.04, 0.06 });
            B.Box(sabre, "blade", matSteel, new[] { 0.02, 0.30, 0.02 }, new[] { 0.06, 0.52, 0.022 },
                Humanoid.O(rx: 6));
            B.ConeEnd(sabre, "tip", matSteel, new[] { 0.03, 0.56, 0.03 }, 0.06, 0.10);

            // 名牌要浮在骑手头顶之上（骑手的头顶已经比马肩隆高，取两者较大者再加 0.2 米）
            Humanoid.Anchor(r, seatY + System.Math.Max(g.Top, q.Withers + 0.10) + U(0.20), U(1.15));
        });
    }

