    // 城齿环：绕矩形顶边一圈
    private static void Crenels(string p, string n, string m, double cx, double cz, double w, double d,
        double y, double step, double h = 0.6, double blk = 0.42)
    {
        var nx = Math.Max(2, (int)Math.Round(w / step));
        var nz = Math.Max(2, (int)Math.Round(d / step));
        for (var i = 0; i < nx; i++)
        foreach (var s in new[] { -1, 1 })
            Tscn.Cbx(p, n, m, new[] { cx - w / 2 + (i + 0.5) * w / nx, y + h / 2, cz + s * (d / 2 - 0.15) },
                new[] { w / nx * blk, h, 0.35 });
        for (var i = 0; i < nz; i++)
        foreach (var s in new[] { -1, 1 })
            Tscn.Cbx(p, n, m, new[] { cx + s * (w / 2 - 0.15), y + h / 2, cz - d / 2 + (i + 0.5) * d / nz },
                new[] { 0.35, h, d / nz * blk });
    }

