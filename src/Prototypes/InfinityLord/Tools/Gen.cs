            BuildTavern(root), BuildApothecary(root), BuildMonsterLair(root), BuildBossLair(root),
            BuildBountyFlag(root),
        };
        var total = 0;
        foreach (var b in built)
        {
            Console.WriteLine($"{b.RootName.PadRight(14)} {b.Count.ToString().PadLeft(4)} nodes");
            total += b.Count;
        }
        Console.WriteLine($"--- total {total} nodes / {built.Count} scenes");
        return 0;
    }
