#nullable enable
using System;
using System.Collections.Generic;
using System.IO;
using DemoFactory.Tools;

namespace DemoFactory.Tools.InfinityLord;

public static class GenPreview
{
    public static int Run(string root, string? clipArg)
    {
        if (string.IsNullOrEmpty(root))
            throw new ArgumentException("usage: dotnet run --project src/Tools -- preview InfinityLord <project-root> [动作名，默认 walk]");
        var clip = string.IsNullOrEmpty(clipArg) ? "walk" : clipArg;
        var dir = $"{root}/src/Prototypes/InfinityLord/Tools/Rigs";
        var genNote = "GENERATED BY src/Prototypes/InfinityLord/Tools/Gen.cs — 勿手改；"
                      + "改脚本后跑 dotnet run --project src/Tools -- preview InfinityLord <项目根>";
        string U(string p) => $"src/Prototypes/InfinityLord/Tools/Rigs/{p}";
        var sun = new[] { -52.0, -28.0, 0.0 };

        // 角色：按体型从小到大排，剪影差异（兜帽长弓 / 扬剑圆盾 / 全罩盔鸢盾 / 三阶地精 / 角盔长矛 / 大肚巨魔）要一眼可辨
        PreviewStage.PreviewScene(new PreviewStage.PreviewInput(
            File: Path.Join(dir, "_PreviewUnits.tscn"), RootName: "PreviewUnits",
            Uid: Uids.Uid.GetValueOrDefault("PreviewUnits"), GenNote: genNote, SunEul: sun,
            Cam: new PreviewStage.Cam(new[] { 2.0, 5.5, 21.0 }, new[] { 2.0, 2.2, 0.0 }, 45),
            Items: new List<PreviewStage.Item>
            {
                new("Ranger", U("Units/Ranger.tscn"), -10.5),
                new("Warrior", U("Units/Warrior.tscn"), -7.5),
                new("Knight", U("Units/Knight.tscn"), -4.5),
                new("Goblin", U("Units/Goblin.tscn"), -1.2),
                new("GoblinElite", U("Units/GoblinElite.tscn"), 1.2),
                new("GoblinBrute", U("Units/GoblinBrute.tscn"), 4.2),
                new("BossGuard", U("Units/BossGuard.tscn"), 8),
                new("Troll", U("Units/Troll.tscn"), 13),
            }));

        // 建筑：环形散开，各自转一个角度，避免正对镜头看不出体量
        PreviewStage.PreviewScene(new PreviewStage.PreviewInput(
            File: Path.Join(dir, "_PreviewBuildings.tscn"), RootName: "PreviewBuildings",
            Uid: Uids.Uid.GetValueOrDefault("PreviewBuildings"), GenNote: genNote, SunEul: sun,
            Cam: new PreviewStage.Cam(new[] { 0.0, 42.0, 82.0 }, new[] { 0.0, 6.0, 10.0 }, 50),
            Items: new List<PreviewStage.Item>
            {
                new("BountyFlag", U("Props/BountyFlag.tscn"), -2, Z: 15),
                new("GuildHall", U("Buildings/GuildHall.tscn"), -17, Ry: 18),
                new("GuildWarrior", U("Buildings/GuildWarrior.tscn"), 17, Ry: -18),
                new("Palace", U("Buildings/Palace.tscn"), 0, Z: -16),
                new("Market", U("Buildings/Market.tscn"), -14, Z: 20, Ry: 34),
                new("Tavern", U("Buildings/Tavern.tscn"), 14, Z: 20, Ry: -34),
                new("Apothecary", U("Buildings/Apothecary.tscn"), -32, Z: 10, Ry: 62),
                new("MonsterLair", U("Buildings/MonsterLair.tscn"), 33, Z: 8, Ry: -66),
                new("BossLair", U("Buildings/BossLair.tscn"), 0, Z: 48, Ry: 180),
            }));

        // 真模型（.glb）验收台：同一个模型摆一排，根节点脚本把第三个参数指定的动作播起来。
        // 动作要在这一排里看相位差 —— 游戏运行时各走各的，一眼看不出走路循环对不对。
        // 用法：dotnet run --project src/Tools -- preview InfinityLord . [idle|walk|run|attack_shoot|death]
        PreviewStage.PreviewScene(new PreviewStage.PreviewInput(
            File: Path.Join(root, "src/Prototypes/InfinityLord/Scenes/_PreviewModels.tscn"),
            RootName: "PreviewModels",
            Uid: Uids.Uid.GetValueOrDefault("PreviewModels"), GenNote: genNote, SunEul: sun,
            RootScript: "src/GugaFramework/Tools/glb/preview_autoplay.gd",
            RootProps: new Dictionary<string, string> { ["clip"] = Tscn.JsonStr(clip) },
            Cam: new PreviewStage.Cam(new[] { 3.6, 2.4, 9.2 }, new[] { 3.6, 0.9, 0 }, 42),
            Items: new List<PreviewStage.Item>
            {
                new("Ranger", "src/Prototypes/InfinityLord/Models/Ranger.glb", 0, Ry: 0),
                new("Ranger2", "src/Prototypes/InfinityLord/Models/Ranger.glb", 1.8, Ry: 40),
                new("Ranger3", "src/Prototypes/InfinityLord/Models/Ranger.glb", 3.6, Ry: 90),
                new("Ranger4", "src/Prototypes/InfinityLord/Models/Ranger.glb", 5.4, Ry: 150),
                new("Ranger5", "src/Prototypes/InfinityLord/Models/Ranger.glb", 7.2, Ry: 200),
            }));
        return 0;
    }
}