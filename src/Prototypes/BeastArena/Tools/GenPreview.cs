// 巨兽竞技场 预览场景生成器：把造型源场景与真模型（.glb）摆进自带相机/灯光/环境的舞台，供近景看剪影与动作。
// 舞台本体在 src/Tools/PreviewStage.cs —— 这里只有「摆哪些件、怎么摆、机位在哪」。
//
// 用法：dotnet run --project src/Tools -- preview BeastArena <项目根> [动作名，默认 walk]
// 两个源场景舞台分开摆：巨兽单独一场（它 19.9 米长，混在镇子那一排里会把两边都挡掉），
// 背上小镇八件一场。真模型验收台一件排四个不同角度 —— 同一件模型在不同机位下
// 十视图之外还可能藏着问题（背面没件、单侧穿模），这一步就是看那个。
//
// 产物落在 Tools/Rigs/_Preview{Crew,Town}.tscn（两个源场景舞台）与
// Scenes/_PreviewModels.tscn（.glb 台，落在 Rigs/ 外面，理由见下）；三个文件都是生成物，
// Check 的占地判定只吃 Units/ 与 Town/ 两个子目录。

#nullable enable
using System;
using System.Collections.Generic;
using System.IO;
using DemoFactory.Tools;

namespace DemoFactory.Tools.BeastArena;

public static class GenPreview
{
    private const string Rigs = "src/Prototypes/BeastArena/Tools/Rigs";
    private const string Models = "src/Prototypes/BeastArena/Models";

    public static int Run(string root, string? clipArg)
    {
        if (string.IsNullOrEmpty(root))
            throw new ArgumentException("usage: dotnet run --project src/Tools -- preview BeastArena <project-root> [动作名，默认 walk]");
        var clip = string.IsNullOrEmpty(clipArg) ? "walk" : clipArg;
        var dir = $"{root}/{Rigs}";
        var genNote = "GENERATED BY src/Prototypes/BeastArena/Tools/Gen.cs — 勿手改；"
                      + "改脚本后跑 dotnet run --project src/Tools -- preview BeastArena <项目根>";
        var sun = new[] { -52.0, -28.0, 0.0 };
        string U(string p) => $"{Rigs}/{p}";

        // 巨兽 + 员工：体量差一个量级（7 米 vs 1.7 米），摆在一条线上正好读出比例
        PreviewStage.PreviewScene(new PreviewStage.PreviewInput(
            File: Path.Join(dir, "_PreviewCrew.tscn"), RootName: "PreviewCrew",
            Uid: Uids.Uid.GetValueOrDefault("PreviewCrew"), GenNote: genNote, SunEul: sun,
            // 机位压低：俯视角才看得见「背上驮着一座镇子」的那块台面
            Cam: new PreviewStage.Cam(new[] { 14.0, 11.0, 26.0 }, new[] { 1.0, 4.6, 0.0 }, 48),
            Items: new List<PreviewStage.Item>
            {
                new("Beast", U("Units/Beast.tscn"), 0, Ry: 24),
                new("Worker", U("Units/Worker.tscn"), 15.5),
            }));

        // 镇上几件静态建筑：环开成两排，各转一个角度，避免正对镜头看不出体量。
        // 2026-10-15：切片 1/2 剩下的六件旧件（采石场/农庄/市集/减速陷阱/箭塔/破口）随旧码退休，
        // 这一排改摆 MVP 十三件里的四件。
        PreviewStage.PreviewScene(new PreviewStage.PreviewInput(
            File: Path.Join(dir, "_PreviewTown.tscn"), RootName: "PreviewTown",
            Uid: Uids.Uid.GetValueOrDefault("PreviewTown"), GenNote: genNote, SunEul: sun,
            Cam: new PreviewStage.Cam(new[] { 9.0, 13.0, 30.0 }, new[] { 0.5, 2.4, 2.0 }, 50),
            Items: new List<PreviewStage.Item>
            {
                new("TownHall", U("Town/TownHall.tscn"), 0, Z: 8),
                new("Arena", U("Town/Arena.tscn"), -7.5, Z: 4, Ry: 18),
                new("Workshop", U("Town/Workshop.tscn"), 7.5, Z: 4, Ry: -18),
                new("Hotel", U("Town/Hotel.tscn"), -5.5, Z: -6, Ry: 40),
                new("Restaurant", U("Town/Restaurant.tscn"), 5.5, Z: -6, Ry: -40),
                new("Church", U("Town/Church.tscn"), 0, Z: -12, Ry: 12),
            }));

        // 真模型（.glb）验收台：巨兽与员工各摆几个角度，根节点脚本把第三个参数指定的动作播起来。
        // 动作要在这一排里看相位差 —— 游戏运行时各走各的，一眼看不出走路循环对不对。
        // 落点定在 Rigs/ **外面**（与另两个原型同口径）：离线校验器会核「引用的场景文件是不是真的存在」，
        // 而 Models/*.glb 要到造型线第 3 步才出 —— 摆进 Rigs/ 的话，preview 一跑 check 就变红。
        PreviewStage.PreviewScene(new PreviewStage.PreviewInput(
            File: Path.Join(root, "src/Prototypes/BeastArena/Scenes/_PreviewModels.tscn"),
            RootName: "PreviewModels",
            Uid: Uids.Uid.GetValueOrDefault("PreviewModels"), GenNote: genNote, SunEul: sun,
            RootScript: "src/GugaFramework/Tools/glb/preview_autoplay.gd",
            RootProps: new Dictionary<string, string> { ["clip"] = Tscn.JsonStr(clip) },
            Cam: new PreviewStage.Cam(new[] { 16.0, 12.0, 30.0 }, new[] { 2.0, 4.4, 0.0 }, 46),
            Items: new List<PreviewStage.Item>
            {
                new("Beast", $"{Models}/Beast.glb", 0, Ry: 0),
                new("Beast2", $"{Models}/Beast.glb", 0, Z: 26, Ry: 90),
                new("Beast3", $"{Models}/Beast.glb", 0, Z: 52, Ry: 180),
                new("Worker", $"{Models}/Worker.glb", 15, Ry: 0),
                new("Worker2", $"{Models}/Worker.glb", 16.6, Ry: 40),
                new("Worker3", $"{Models}/Worker.glb", 18.2, Ry: 90),
            }));
        return 0;
    }
}
